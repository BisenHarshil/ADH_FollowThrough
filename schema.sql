create table if not exists users (
  id bigint generated by default as identity primary key,
  email text not null unique,
  name text not null default '',
  password_hash text not null,
  created_at timestamptz not null default now()
);

create table if not exists conversations (
  id bigint generated by default as identity primary key,
  user_id text,
  text text not null,
  engine text not null default 'rules',
  created_at timestamptz not null default now()
);

create table if not exists tasks (
  id bigint generated by default as identity primary key,
  user_id text,
  conversation_id bigint references conversations(id) on delete cascade,
  title text not null,
  due text not null default 'No date',
  due_date date,
  who text not null default '',
  priority text not null default 'normal',
  source text not null default '',
  server_id text not null,
  done boolean not null default false,
  created_at timestamptz not null default now()
);

-- If you created these tables with the previous version, add the new column:
alter table conversations add column if not exists user_id text;
alter table tasks add column if not exists user_id text;

-- Passwords are hashed by the app, but keep the Supabase key SERVER-SIDE ONLY
-- (use the service_role key here, never ship it to the browser).
alter table users enable row level security;
alter table conversations enable row level security;
alter table tasks enable row level security;
